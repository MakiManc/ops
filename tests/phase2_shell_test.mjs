// Phase 2 in both shells (11/10/2026): the supplier statements and OO4 KR5.
//
//   * Supplier Issues tab: a card listing the monthly statements (Final /
//     Provisional, retrospective ones marked not scored) and the weekly Lynas
//     cuts, each linked to GitHub's rendering of its .md, with the .json beside
//     it - and a plain sentence for a snapshot from before the statements.
//   * Scorecard (index.html) and OKR wall (okr.html): a row the builder links to
//     a document (OO3 KR5 -> the month's statement) shows that link for the
//     month picked - and only an https link, so a bad href in a snapshot can
//     never become a javascript: link on the page.
//   * Supply tab: OO4 KR5's unweighted mean is a second total row of the
//     issue-free table it is computed from.
// Booted for real against served fixtures (window.OPS_BASE + route
// interception, clock pinned), patched from the newest committed snapshot.
import { chromium } from 'playwright';
import { readFileSync, existsSync, readdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(__dirname, '..');
const indexUrl = 'file://' + path.join(repoRoot, 'command', 'index.html');
const okrUrl = 'file://' + path.join(repoRoot, 'command', 'okr.html');
const snapDir = path.join(repoRoot, 'data', 'ops_command');
const latestSnap = readdirSync(snapDir)
  .filter(f => /^snapshot_\d{4}-\d{2}-\d{2}\.json$/.test(f)).sort().pop();
const baseSnap = JSON.parse(readFileSync(path.join(snapDir, latestSnap), 'utf-8'));

let failures = 0;
function assert(cond, msg) {
  if (!cond) { failures++; console.error('FAIL:', msg); }
  else console.log('ok  :', msg);
}
const clone = o => JSON.parse(JSON.stringify(o));
const pinnedChromium = '/opt/pw-browsers/chromium-1194/chrome-linux/chrome';
const browser = await chromium.launch(existsSync(pinnedChromium) ? { executablePath: pinnedChromium } : {});

const DATE = '2026-10-11';
const BLOB = 'https://github.com/MakiManc/ops/blob/main/data/ops_command/';
const v = (m, kw) => ({ m, label: m, value: null, display: null, score: null, rag: null, basis: null,
  trend: null, trend_unit: null, trend_note: null, not_measured: null, ...kw });

function fixture({ statements = true } = {}) {
  const s = clone(baseSnap);
  s.pull_date = DATE; s.generated_at = DATE + 'T15:00:00Z';
  s.feed_health = (s.feed_health || []).map(r => ({ ...r, age_days: 0 }));
  const sc = s.scorecard;
  sc.month = '2026-10';
  for (const m of ['2026-08', '2026-09']) if (!sc.months.includes(m)) sc.months.push(m);
  sc.months.sort().reverse();
  const row = (o, k) => sc.rows.find(r => r.objective === o && r.kr === k);
  const link9 = { href: BLOB + 'supplier_statements/2026-09.md', label: 'September 2026 statement' };
  Object.assign(row('OO3', 'KR5'), {
    source_kind: 'computed', tab: 'p-supi', value: null, display: null, score: null, rag: null,
    mtd: true, not_measured: null, link: null,
    basis: "not due yet - October 2026's supplier statement is generated by the first bake on or after 1 November 2026",
    months: [
      v('2026-08', { not_measured: 'not scored - supplier statements began with Phase 2 in October 2026' }),
      v('2026-09', { link: link9, not_measured: 'not scored - supplier statements began with Phase 2 in October 2026, so no statement for September 2026 existed by its due date; one was generated retrospectively on 2026-10-11' }),
      v('2026-10', { mtd: true, basis: "not due yet - October 2026's supplier statement is generated by the first bake on or after 1 November 2026" }),
    ],
  });
  // a hostile href must never become a link
  Object.assign(row('OO4', 'KR2'), {
    source_kind: 'computed', value: 0, display: '0', score: null, rag: null, mtd: true,
    link: { href: 'javascript:alert(1)', label: 'EVIL' },
    basis: 'month-to-date, not yet scored - 0 forms matched',
    months: [v('2026-09', { value: 0, display: '0+', link: { href: 'javascript:alert(1)', label: 'EVIL' },
                            basis: 'not scored - an INCOMPLETE month' }),
             v('2026-10', { value: 0, display: '0', mtd: true, link: { href: 'javascript:alert(1)', label: 'EVIL' },
                            basis: 'month-to-date, not yet scored - 0 forms matched' })],
  });
  for (const o of sc.objectives)
    for (const m of ['2026-08', '2026-09'])
      if (!o.months.find(x => x.m === m)) o.months.push({ m, pct: null, scored: 0, total: 5 });
  const om = (s.supply.otif.months || []).slice(-1)[0];
  if (om) Object.assign(om, { supplier_mean: 97.3, supplier_mean_of: 15 });
  if (statements) s.suppliers.statements = {
    monthly: [{ month: '2026-09', generated_on: '2026-10-11', updated_on: '2026-10-11', final: true,
                retrospective: true, forms: 74, suppliers: 17, suppliers_named: 8,
                json: 'supplier_statements/2026-09.json', md: 'supplier_statements/2026-09.md',
                url: BLOB + 'supplier_statements/2026-09.md' }],
    weekly: [{ week: '2026-W40', from: '2026-09-28', to: '2026-10-04', supplier: 'Lynas',
               generated_on: '2026-10-11', final: true, forms: 7, rate: 89.9,
               md: 'supplier_statements/weekly/2026-W40-Lynas.md',
               url: BLOB + 'supplier_statements/weekly/2026-W40-Lynas.md' }],
    lynas_weekly: true, scored_from: '2026-10',
    basis: 'one statement per closed month, generated by the first bake on or after the 1st',
  };
  else delete s.suppliers.statements;
  return s;
}

async function boot(url, snap) {
  const page = await browser.newPage({ viewport: { width: 1400, height: 1000 } });
  const errors = [];
  page.on('pageerror', e => errors.push(String(e)));
  await page.clock.setFixedTime(new Date(DATE + 'T14:00:00Z'));
  await page.addInitScript(() => { window.OPS_BASE = 'http://fixtures.test/'; });
  await page.route('http://fixtures.test/**', route => {
    const name = new URL(route.request().url()).pathname.slice(1);
    if (name === 'snapshot_index.json')
      return route.fulfill({ status: 200, contentType: 'application/json',
        body: JSON.stringify({ latest: DATE, dates: [DATE], generated_at: DATE + 'T15:00:00Z' }) });
    if (name === `snapshot_${DATE}.json`)
      return route.fulfill({ status: 200, contentType: 'application/json', body: JSON.stringify(snap) });
    return route.fulfill({ status: 404, body: 'not found' });
  });
  await page.goto(url);
  await page.waitForTimeout(1200);
  page._errors = errors;
  return page;
}

// ---- index.html: the Supplier Issues card ------------------------------------
{
  const page = await boot(indexUrl, fixture());
  await page.evaluate(() => window.gotoPage('p-supi'));
  await page.waitForTimeout(300);
  const card = page.locator('#sq-stmt');
  const txt = await card.innerText();
  assert(/September 2026/.test(txt) && /Final/.test(txt) && /Retrospective · not scored/.test(txt)
    && /2026-10-11/.test(txt) && /\b74\b/.test(txt) && /\b8\b/.test(txt),
    'the statement row: month, Final, retrospective-not-scored, generated date, 74 forms, 8 suppliers named');
  const links = await card.locator('a').evaluateAll(as => as.map(a => ({ t: a.innerText, h: a.href, tg: a.target })));
  const st = links.find(l => /^Statement/.test(l.t));
  assert(st && st.h === BLOB + 'supplier_statements/2026-09.md' && st.tg === '_blank',
    `"Statement" opens GitHub's rendering of the .md in a new tab (got ${st && st.h})`);
  const data = links.find(l => l.t === 'data');
  assert(data && data.h === 'http://fixtures.test/supplier_statements/2026-09.json',
    `"data" is the .json beside it, from the same base as the snapshot (got ${data && data.h})`);
  assert(/Lynas, week by week/.test(txt) && /2026-W40/.test(txt) && /89\.9%/.test(txt)
    && links.some(l => /^Lynas cut/.test(l.t) && l.h.endsWith('2026-W40-Lynas.md')),
    'the weekly Lynas cut is listed with its issue-free rate and its link');
  assert(page._errors.length === 0, 'no page errors (Supplier Issues)' + (page._errors.length ? ': ' + page._errors.join(' | ') : ''));
  await page.close();

  const old = await boot(indexUrl, fixture({ statements: false }));
  await old.evaluate(() => window.gotoPage('p-supi'));
  await old.waitForTimeout(300);
  assert(/predates the supplier statements/.test(await old.locator('#sq-stmt').innerText()),
    'a snapshot from before Phase 2 says it predates the statements - no empty table');
  assert(old._errors.length === 0, 'no page errors on an old snapshot');
  await old.close();
}

// ---- index.html: the scorecard link and OO4 KR5's mean row --------------------
{
  const page = await boot(indexUrl, fixture());
  await page.selectOption('#sc-month', '2026-09');
  await page.waitForTimeout(300);
  const rows = await page.locator('#scorecard tbody tr').evaluateAll(trs => trs.map(tr => ({
    text: tr.innerText, links: [...tr.querySelectorAll('a')].map(a => ({ t: a.innerText, h: a.getAttribute('href') })) })));
  const k5 = rows.find(r => /Monthly Supplier Audit Completion/.test(r.text));
  assert(k5 && k5.links.some(l => /September 2026 statement/.test(l.t) && l.h === BLOB + 'supplier_statements/2026-09.md'),
    'September: OO3 KR5 links the September statement');
  assert(k5 && /generated retrospectively/.test(k5.text), '...and says why it is not scored');
  const k2 = rows.find(r => /critical SKUs damaged/.test(r.text));
  assert(k2 && !k2.links.length && !/EVIL/.test(k2.text), 'a javascript: href in the snapshot is not rendered as a link');
  await page.selectOption('#sc-month', '2026-10');
  await page.waitForTimeout(300);
  const k5o = (await page.locator('#scorecard tbody tr').evaluateAll(trs => trs.map(tr => ({
    text: tr.innerText, n: tr.querySelectorAll('a').length })))).find(r => /Monthly Supplier Audit Completion/.test(r.text));
  assert(k5o && k5o.n === 0 && /not due yet/.test(k5o.text), 'October: no statement yet - no link, "not due yet"');

  await page.evaluate(() => window.gotoPage('p-supp'));
  await page.waitForTimeout(300);
  const tot = await page.locator('#otif-tbl tr.tot').evaluateAll(trs => trs.map(tr => tr.innerText));
  assert(tot.length === 2 && /Unweighted mean/.test(tot[1]) && /OO4 KR5/.test(tot[1]) && /97\.3%/.test(tot[1])
    && /15 measurable suppliers counts once/.test(tot[1]),
    `the issue-free table carries OO4 KR5's unweighted mean as a second total row (got ${JSON.stringify(tot)})`);
  assert(page._errors.length === 0, 'no page errors (scorecard, supply)' + (page._errors.length ? ': ' + page._errors.join(' | ') : ''));
  await page.close();
}

// ---- okr.html -----------------------------------------------------------------
{
  const page = await boot(okrUrl + '?m=2026-09', fixture());
  const cards = await page.locator('.kr').evaluateAll(ds => ds.map(d => ({
    t: d.querySelector('.t')?.innerText || '',
    lk: [...d.querySelectorAll('.lk a')].map(a => ({ t: a.innerText, h: a.getAttribute('href'), tg: a.target })) })));
  const k5 = cards.find(c => /Monthly Supplier Audit Completion/.test(c.t));
  assert(k5 && k5.lk.length === 1 && k5.lk[0].h === BLOB + 'supplier_statements/2026-09.md'
    && /September 2026 statement/.test(k5.lk[0].t) && k5.lk[0].tg === '_blank',
    'the wall\'s OO3 KR5 card links the September statement');
  const k2 = cards.find(c => /critical SKUs damaged/.test(c.t));
  assert(k2 && k2.lk.length === 0, 'and never renders a javascript: link');
  assert(page._errors.length === 0, 'no page errors on okr.html' + (page._errors.length ? ': ' + page._errors.join(' | ') : ''));
  await page.close();
  const tv = await boot(okrUrl + '?m=2026-09&tv=1', fixture());
  const hidden = await tv.locator('.kr .lk').first().evaluate(e => getComputedStyle(e).display).catch(() => 'none');
  const isTv = await tv.evaluate(() => document.body.classList.contains('tv'));
  assert(isTv && hidden === 'none', `on the TV wall the link line is hidden - nothing to click (tv=${isTv}, display=${hidden})`);
  await tv.close();
}

await browser.close();
console.log(failures ? `\n${failures} FAILURE(S)` : '\nall passed');
process.exit(failures ? 1 : 0);
