#!/usr/bin/env python3
"""Monthly supplier statements (OO3 KR5) and the weekly Lynas cut (Phase 2).

WHAT A STATEMENT IS (Ross's brief, 2.1). For the month just closed, one file
per month - data/ops_command/supplier_statements/<YYYY-MM>.json and a readable
.md beside it - holding, per supplier: the forms raised against it by site and
by category, every issue's VERBATIM text, the rows that mention a credit or an
invoice, and that supplier's issue-free delivery rate for the month (the same
supply.otif figure the Supply tab shows). It is generated by the first bake on
or after the 1st, and OO3 KR5 scores HOW SOON: by the 3rd -> 100, by the
10th -> 50, otherwise 0 (OKR_BANDS 'audit': the value is the DAY of the
following month the statement was generated on).

WHAT IT IS NOT. Not an audit of the supplier in any wider sense, and the rate
is NOT OTIF - see supply.otif.basis, quoted into every statement. It is the
month's evidence in one place, so the conversation with the supplier can start
from the same rows the dashboard counts.

THE RULES THIS FILE KEEPS.
  * Only a LIVE (undated) bake writes. A back-bake reads what exists, and
    counts a statement only if it was generated on or before the bake's date
    - a back-bake of 2 October must not "find" a statement written on the 12th.
  * generated_on is set ONCE, when the file first appears, and never moves:
    it is the KR's measurement. A statement made while the issue feed did not
    yet reach the month's last day is PROVISIONAL and later bakes refresh its
    contents (updated_on) until the feed does; then it is FINAL and frozen.
  * Months before the statements existed are not scored. The first scored
    month is STATEMENTS_SCORED_FROM; an earlier month's statement, generated
    after the fact, is marked retrospective and its KR month says why, rather
    than scoring a 0 that only measures the day this code shipped.
  * Verbatim means verbatim - the issue text is not edited, summarised or
    re-categorised. The markdown escapes only what would break rendering
    (table pipes, HTML, and Liquid braces: GitHub Pages runs Jekyll, and a
    stray '{{' in an issue would fail the whole site's build).

The weekly cut (supplier_statements/weekly/<YYYY>-W<ww>-Lynas.md, plus a .json
sidecar holding its dates) is written by the first live bake on or after each
Monday for the ISO week just ended, while LYNAS_WEEKLY_CUT is on - Ross's
Lynas exit. It is not scored.
"""
from __future__ import annotations

import datetime
import json
import os
import re

STATEMENTS_DIR = "supplier_statements"
WEEKLY_DIR = "weekly"
#: The first month whose statement OO3 KR5 scores. Phase 2 shipped in
#: October 2026, so October's statement (due 1-3 November) is the first that
#: could be on time; September's is generated retrospectively and not scored.
STATEMENTS_SCORED_FROM = "2026-10"
#: The first month a statement can describe: the issue-answer feed's first.
STATEMENTS_FIRST_MONTH = "2026-08"
#: Ross's Lynas exit is live (Phase 2 brief). Turn this off when it is over;
#: the files already written stay.
LYNAS_WEEKLY_CUT = True
LYNAS = "Lynas"
#: Where the readable copy lives. GitHub renders the markdown; the Pages copy
#: of a .md is whatever Jekyll makes of it, which this repo does not control.
BLOB = "https://github.com/MakiManc/ops/blob/main/data/ops_command/"
#: An issue that mentions money owed or charged. Matched on the verbatim text,
#: as well as the keyword category 'invoice_credit', because a shortage that
#: asks for a credit is categorised 'shortage' and is still a credit row.
CREDIT_RE = re.compile(r"credit|invoice|refund|overcharg|\bcharged\b|\brebate\b", re.I)

_MONTHS = ("January", "February", "March", "April", "May", "June", "July",
           "August", "September", "October", "November", "December")


def mlabel(ym: str) -> str:
    return f"{_MONTHS[int(ym[5:7]) - 1]} {ym[:4]}"


def month_bounds(ym: str) -> tuple[str, str]:
    y, m = int(ym[:4]), int(ym[5:7])
    nxt = datetime.date(y + (m == 12), 1 if m == 12 else m + 1, 1)
    return f"{ym}-01", (nxt - datetime.timedelta(days=1)).isoformat()


def next_month(ym: str) -> str:
    y, m = int(ym[:4]), int(ym[5:7])
    return f"{y + (m == 12)}-{1 if m == 12 else m + 1:02d}"


def prev_month(ym: str) -> str:
    y, m = int(ym[:4]), int(ym[5:7])
    return f"{y - (m == 1)}-{12 if m == 1 else m - 1:02d}"


def short_day(d: str) -> str:
    x = datetime.date.fromisoformat(d[:10])
    return f"{x.day} {x.strftime('%b')}"


def credit_flag(issue: dict) -> bool:
    return (issue.get("category") == "invoice_credit"
            or bool(CREDIT_RE.search(issue.get("issue_text") or "")))


def md_cell(s) -> str:
    """One table cell, safe for GitHub markdown AND for Jekyll's Liquid.

    Brackets too (review, 11/10/2026): Pages renders each .md to HTML with
    kramdown, which does no URL filtering, so an issue typed as
    '[x](javascript:...)' or '![x](https://...)' became a live link or a remote
    image on the dashboard's own origin."""
    t = "" if s is None else str(s)
    t = (t.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
          .replace("{", "&#123;").replace("}", "&#125;").replace("|", "\\|")
          .replace("[", "&#91;").replace("]", "&#93;"))
    return " ".join(t.split())


def _issue_row(i: dict) -> dict:
    return {"d": i.get("d"), "site": i.get("site"), "category": i.get("category"),
            "open": bool(i.get("open")), "attribution": i.get("attribution"),
            "form": i.get("form"), "text": i.get("issue_text"),
            "credit_flag": credit_flag(i)}


def _count(rows, key):
    out = {}
    for r in rows:
        k = r.get(key) or "(none recorded)"
        out[k] = out.get(k, 0) + 1
    return [{key: k, "forms": n} for k, n in sorted(out.items(), key=lambda kv: (-kv[1], kv[0]))]


def _supplier_block(name, rows, otif_row):
    rows = sorted(rows, key=lambda r: (r["d"] or "", r["site"] or ""))
    rate = None
    if otif_row is not None:
        rate = {"deliveries": otif_row.get("deliveries"), "issues": otif_row.get("issues"),
                "rate": otif_row.get("otif_pct"), "measurable": bool(otif_row.get("measurable")),
                "not_measured": otif_row.get("not_measured")}
    return {"supplier": name, "forms": len(rows),
            "by_site": _count(rows, "site"), "by_category": _count(rows, "category"),
            "credit_flagged": sum(1 for r in rows if r["credit_flag"]),
            "issue_free": rate, "issues": rows}


def coverage(ym, through, holes, feed_first):
    """How much of month ym the issue-answer feed has seen, in words + a flag."""
    ms, me = month_bounds(ym)
    hs = [d for d in (holes or ()) if ms <= d <= me]
    notes = []
    if feed_first and ms < feed_first <= me:
        notes.append(f"the issue-answer feed starts {feed_first}, so nothing raised before it is here")
    if hs:
        notes.append("no pull of the issue-answer feed covers " + ", ".join(hs)
                     + ", so issues raised on those days are missing")
    complete = bool(through) and through[:10] >= me
    if not complete:
        notes.append(f"the issue-answer feed reaches only {through or 'no day at all'}, so "
                     "the month's last days are not in yet - PROVISIONAL, refreshed by later "
                     "bakes until the feed reaches the month end")
    return complete, hs, notes


def month_statement(ym, issues, otif_month, through, holes, feed_first,
                    generated_on, updated_on, otif_basis=None):
    """The statement document for month ym. Pure: no file is touched."""
    rows = [i for i in issues if (i.get("d") or "")[:7] == ym]
    by_sup = {}
    unatt = []
    for i in rows:
        if i.get("supplier"):
            by_sup.setdefault(i["supplier"], []).append(_issue_row(i))
        else:
            unatt.append(_issue_row(i))
    otif_rows = {r.get("supplier"): r for r in ((otif_month or {}).get("suppliers") or [])}
    names = set(by_sup) | set(otif_rows)
    blocks = [_supplier_block(n, by_sup.get(n, []), otif_rows.get(n)) for n in names]
    blocks.sort(key=lambda b: (-b["forms"], -((b["issue_free"] or {}).get("deliveries") or 0),
                               b["supplier"]))
    complete, hs, notes = coverage(ym, through, holes, feed_first)
    ms, me = month_bounds(ym)
    return {
        "kind": "supplier_statement", "month": ym, "label": mlabel(ym),
        "generated_on": generated_on, "updated_on": updated_on,
        "final": complete, "retrospective": ym < STATEMENTS_SCORED_FROM,
        "issue_feed_through": through, "feed_holes": hs, "coverage_notes": notes,
        "forms": len(rows), "suppliers": len(blocks),
        # suppliers NAMED on at least one form - `suppliers` also counts the
        # ones that only delivered, which a "forms across N suppliers" line
        # must not use
        "suppliers_named": sum(1 for b in blocks if b["forms"]),
        "credit_flagged": sum(1 for b in blocks for r in b["issues"] if r["credit_flag"])
                          + sum(1 for r in unatt if r["credit_flag"]),
        "supplier_blocks": blocks,
        "unattributed": {"forms": len(unatt), "issues": unatt},
        "basis": ("Every delivery/supplier issue form in GetCompliant whose own answer date "
                  f"falls in {mlabel(ym)} ({ms} to {me}), deduped by FormId - the same rows the "
                  "Supplier Issues tab and OO3 KR1 count - grouped by the supplier answered on "
                  "the form (or found in its text when the question was left blank). Issue text "
                  "is VERBATIM. Category is a keyword heuristic over that text, not a "
                  "taxonomy. A row is credit/invoice-flagged when its text mentions a credit, "
                  "invoice, refund, rebate or charge, or its category is invoice_credit. The "
                  "issue-free rate is supply.otif's for the month and is NOT on-time-in-full"
                  + (": " + otif_basis if otif_basis else "")),
    }


def _md_rate(r):
    if not r:
        return "no Kobas order emails for this supplier in the month - no rate"
    if r.get("rate") is None:
        return f"not measured - {r.get('not_measured') or 'no rate for this month'}"
    return (f"{r['rate']:.1f}% ({r.get('deliveries')} deliveries, {r.get('issues')} issue "
            "form(s))")


def _md_issue_table(rows, as_at=None):
    # "Open" is GetCompliant's state on the day the file was written, and a
    # FINAL statement is never rewritten - so the header says which day.
    out = [f"| Date | Site | Category | Open{' at ' + as_at if as_at else ''} | Credit/invoice "
           "| Issue (verbatim) |",
           "|---|---|---|---|---|---|"]
    for r in rows:
        out.append(f"| {md_cell(r['d'])} | {md_cell(r['site'] or '-')} | "
                   f"{md_cell(r['category'] or '-')} | {'yes' if r['open'] else 'no'} | "
                   f"{'yes' if r['credit_flag'] else ''} | {md_cell(r['text'] or '(no text)')} |")
    return out


def statement_md(doc: dict) -> str:
    st = "FINAL" if doc["final"] else "PROVISIONAL"
    L = [f"# Supplier statement - {md_cell(doc['label'])}", "",
         f"**{st}** · generated {doc['generated_on']}"
         + (f" · updated {doc['updated_on']}" if doc.get("updated_on") != doc["generated_on"] else "")
         + (" · retrospective (statements began in October 2026; this one is not scored)"
            if doc.get("retrospective") else ""), ""]
    for n in doc.get("coverage_notes") or []:
        L.append(f"> {md_cell(n)}")
    if doc.get("coverage_notes"):
        L.append("")
    L += [f"{doc['forms']} issue form(s): {doc['forms'] - doc['unattributed']['forms']} "
          f"name one of {doc['suppliers_named']} supplier(s) and "
          f"{doc['unattributed']['forms']} name none; {doc['credit_flagged']} mention a "
          f"credit or an invoice. {doc['suppliers']} supplier(s) delivered or were named in "
          "the month, and every one is listed below.", "",
          "| Supplier | Issue forms | Sites | Credit/invoice rows | Issue-free delivery rate |",
          "|---|---:|---:|---:|---|"]
    for b in doc["supplier_blocks"]:
        L.append(f"| {md_cell(b['supplier'])} | {b['forms']} | {len(b['by_site'])} | "
                 f"{b['credit_flagged']} | {md_cell(_md_rate(b['issue_free']))} |")
    L.append("")
    for b in doc["supplier_blocks"]:
        if not b["forms"]:
            continue
        L += [f"## {md_cell(b['supplier'])}", "",
              f"Issue-free delivery rate: {md_cell(_md_rate(b['issue_free']))}", "",
              "Forms by site: " + "; ".join(f"{md_cell(x['site'])} {x['forms']}"
                                            for x in b["by_site"]), "",
              "By category (keyword heuristic): " + "; ".join(
                  f"{md_cell(x['category'])} {x['forms']}" for x in b["by_category"]), ""]
        L += _md_issue_table(b["issues"], doc.get("updated_on")) + [""]
    quiet = [b["supplier"] for b in doc["supplier_blocks"] if not b["forms"]]
    if quiet:
        L += ["## No issue forms this month", "",
              "; ".join(f"{md_cell(b['supplier'])} - {md_cell(_md_rate(b['issue_free']))}"
                        for b in doc["supplier_blocks"] if not b["forms"]), ""]
    if doc["unattributed"]["forms"]:
        L += ["## Forms that named no supplier", ""] + _md_issue_table(
            doc["unattributed"]["issues"], doc.get("updated_on")) + [""]
    L += ["---", "", f"Basis: {md_cell(doc['basis'])}", ""]
    return "\n".join(L)


def iso_week(d: datetime.date) -> tuple[str, str, str]:
    """('2026-W41', monday, sunday) for the ISO week holding d."""
    y, w, _ = d.isocalendar()
    mon = d - datetime.timedelta(days=d.weekday())
    return f"{y}-W{w:02d}", mon.isoformat(), (mon + datetime.timedelta(days=6)).isoformat()


def week_cut(week, mon, sun, issues, deliveries_by_day, first_dd, through, holes,
             generated_on, updated_on):
    rows = sorted((_issue_row(i) for i in issues
                   if i.get("supplier") == LYNAS and mon <= (i.get("d") or "") <= sun),
                  key=lambda r: (r["d"] or "", r["site"] or ""))
    hs = [d for d in (holes or ()) if mon <= d <= sun]
    complete = bool(through) and through[:10] >= sun
    dl = sum(n for (d, s), n in deliveries_by_day.items() if s == LYNAS and mon <= d <= sun)
    dl_counted = sum(n for (d, s), n in deliveries_by_day.items()
                     if s == LYNAS and mon <= d <= sun and d <= (through or "")[:10]
                     and d not in hs)
    why = None
    if not first_dd or first_dd > mon:
        why = (f"Lynas order emails only start {first_dd or 'never'}, so the week's "
               "deliveries are a fragment")
    elif hs:
        why = "no pull of the issue feed covers " + ", ".join(hs)
    elif not complete:
        why = f"the issue feed reaches only {through or 'no day'} - the week is not all in yet"
    elif not dl_counted:
        why = "no Lynas delivery dated in the week"
    rate = None if why else round(100.0 * max(0, dl_counted - len(rows)) / dl_counted, 1)
    return {"kind": "lynas_weekly_cut", "week": week, "from": mon, "to": sun,
            "generated_on": generated_on, "updated_on": updated_on, "final": complete,
            "issue_feed_through": through, "forms": len(rows),
            "deliveries": dl, "deliveries_counted": dl_counted,
            "rate": rate, "not_measured": why,
            "credit_flagged": sum(1 for r in rows if r["credit_flag"]),
            "by_site": _count(rows, "site"), "by_category": _count(rows, "category"),
            "issues": rows,
            "basis": ("Lynas issue forms whose own answer date falls in the ISO week (Monday to "
                      "Sunday), the same rows as the monthly statement; deliveries are Lynas "
                      "orders in the Kobas order-confirmation emails with a delivery date in the "
                      "week, counted for the rate only up to the newest day the issue feed "
                      "covers. Rate = max(0, deliveries - issue forms) / deliveries - an "
                      "issue-free rate, NOT on-time-in-full.")}


def week_md(doc: dict) -> str:
    st = "FINAL" if doc["final"] else "PROVISIONAL"
    rate = (f"{doc['rate']:.1f}%" if doc["rate"] is not None
            else f"not measured - {doc['not_measured']}")
    L = [f"# Lynas - week {doc['week'][-2:]} ({short_day(doc['from'])} to "
         f"{short_day(doc['to'])} {doc['to'][:4]})", "",
         f"**{st}** · generated {doc['generated_on']}"
         + (f" · updated {doc['updated_on']}" if doc.get("updated_on") != doc["generated_on"] else ""),
         "",
         f"Deliveries (Kobas order emails, by delivery date): {doc['deliveries']} · "
         f"issue forms: {doc['forms']} · credit/invoice rows: {doc['credit_flagged']} · "
         f"issue-free rate: {md_cell(rate)}", ""]
    if doc["forms"]:
        L += ["Forms by site: " + "; ".join(f"{md_cell(x['site'])} {x['forms']}"
                                             for x in doc["by_site"]), "",
              "By category (keyword heuristic): " + "; ".join(
                  f"{md_cell(x['category'])} {x['forms']}" for x in doc["by_category"]), ""]
        L += _md_issue_table(doc["issues"], doc.get("updated_on")) + [""]
    else:
        L += ["No Lynas issue form was answered in this week.", ""]
    L += ["---", "", f"Basis: {md_cell(doc['basis'])}", ""]
    return "\n".join(L)


def _read_json(path):
    st, d = _load(path)
    return d if st == "ok" else None


def _load(path):
    """('missing', None), ('bad', None) or ('ok', dict). A file that exists but
    does not parse is NOT missing: overwriting it would reset generated_on, the
    KR's measurement, so the caller leaves it alone and says so."""
    if not os.path.exists(path):
        return "missing", None
    try:
        with open(path, encoding="utf-8") as fh:
            d = json.load(fh)
    except (OSError, ValueError):
        return "bad", None
    return ("ok", d) if isinstance(d, dict) and d.get("generated_on") else ("bad", None)


def _write(path, text):
    os.makedirs(os.path.dirname(path) or ".", exist_ok=True)
    tmp = path + ".tmp"
    with open(tmp, "w", encoding="utf-8") as fh:
        fh.write(text)
    os.replace(tmp, path)


#: How far back a live bake looks for a statement or cut that is missing or
#: still PROVISIONAL (review, 11/10/2026): a bake that did not push for a few
#: days, or a feed that reached the period's end late, must not leave a gap or
#: a provisional file for good. Beyond this it is history, left as it is.
MONTH_LOOKBACK = 2
WEEK_LOOKBACK = 4


def sync(out_dir, today, dated, issues, otif_months, through, holes, feed_first,
         deliveries_by_day, first_dd, otif_basis=None, forbidden=(), pull=None):
    """Write what is due (live bakes only) and return the index the snapshot
    carries: {"monthly": [...], "weekly": [...], "written": [...], "gaps": [...]}.

    today      the bake's real date (YYYY-MM-DD); for a dated bake, its date
    dated      the --date of a back-bake, or None for a live bake
    pull       the bake's pull date: nothing is written for a period the data
               has not left yet (a bake on the 1st whose newest pull is still
               the 31st waits for the next one)
    forbidden  strings that must never be written (OO1's Finance column names)
    """
    sdir = os.path.join(out_dir, STATEMENTS_DIR)
    written, gaps = [], []
    if dated:
        return {**index(out_dir, dated), "written": written, "gaps": gaps}
    pull = (pull or today)[:10]

    def _guard(text, what):
        bad = [n for n in forbidden if n in text]
        if bad:
            raise SystemExit(f"[bake] REFUSING TO WRITE {what}: it carries "
                             + ", ".join(repr(n) for n in bad))

    def _due(jp, what):
        st, old = _load(jp)
        if st == "bad":
            gaps.append(f"{what}: {os.path.relpath(jp, out_dir)} exists but cannot be read, so "
                        "it is left as it is rather than rewritten with a new generated_on - "
                        "restore it from git history")
            return False, None
        return (old is None or not old.get("final")), old

    # ---- closed months: the one just closed, and the one before it ----------
    ym = today[:7]
    for _ in range(MONTH_LOOKBACK):
        ym = prev_month(ym)
        if ym < STATEMENTS_FIRST_MONTH or ym >= pull[:7]:
            continue
        if not through or through[:10] < f"{ym}-01":
            # the issue feed has not reached the month at all: a statement now
            # would be empty, and would still score on the day it was written
            continue
        jp = os.path.join(sdir, f"{ym}.json")
        go, old = _due(jp, f"The {mlabel(ym)} supplier statement")
        if not go:
            continue
        om = next((m for m in otif_months or [] if m.get("month") == ym), None)
        doc = month_statement(ym, issues, om, through, holes, feed_first,
                              generated_on=(old or {}).get("generated_on") or today,
                              updated_on=today, otif_basis=otif_basis)
        doc["final_on"] = (old or {}).get("final_on") or (today if doc["final"] else None)
        js = json.dumps(doc, indent=1, ensure_ascii=False)
        md = statement_md(doc)
        _guard(js + md, f"the {ym} supplier statement")
        _write(jp, js + "\n")
        _write(os.path.join(sdir, f"{ym}.md"), md)
        written += [jp, os.path.join(sdir, f"{ym}.md")]

    # ---- the Lynas weeks just ended -----------------------------------------
    if LYNAS_WEEKLY_CUT:
        t = datetime.date.fromisoformat(today[:10])
        wdir = os.path.join(sdir, WEEKLY_DIR)
        for k in range(1, WEEK_LOOKBACK + 1):
            week, mon, sun = iso_week(t - datetime.timedelta(days=7 * k))
            if sun >= pull:
                continue
            jp = os.path.join(wdir, f"{week}-{LYNAS}.json")
            go, old = _due(jp, f"The {week} Lynas cut")
            if not go:
                continue
            doc = week_cut(week, mon, sun, issues, deliveries_by_day, first_dd.get(LYNAS),
                           through, holes, generated_on=(old or {}).get("generated_on") or today,
                           updated_on=today)
            doc["final_on"] = (old or {}).get("final_on") or (today if doc["final"] else None)
            js = json.dumps(doc, indent=1, ensure_ascii=False)
            md = week_md(doc)
            _guard(js + md, f"the {week} Lynas cut")
            _write(jp, js + "\n")
            _write(os.path.join(wdir, f"{week}-{LYNAS}.md"), md)
            written += [jp, os.path.join(wdir, f"{week}-{LYNAS}.md")]

    return {**index(out_dir, dated), "written": written, "gaps": gaps}


def index(out_dir, dated=None):
    """What exists, as of `dated` (a back-bake sees nothing generated later)."""
    sdir = os.path.join(out_dir, STATEMENTS_DIR)
    monthly, weekly = [], []
    for name in sorted(os.listdir(sdir)) if os.path.isdir(sdir) else []:
        if not re.fullmatch(r"\d{4}-\d{2}\.json", name):
            continue
        d = _read_json(os.path.join(sdir, name))
        if not d or not d.get("generated_on") or (dated and d["generated_on"] > dated):
            continue
        ym = name[:7]
        monthly.append({"month": ym, "generated_on": d["generated_on"],
                        # a back-bake reads TODAY's copy: when it was updated after
                        # the bake's date, its contents and status are later news
                        "updated_after": (d.get("updated_on") if dated and
                                          (d.get("updated_on") or "") > dated else None),
                        "updated_on": d.get("updated_on"), "final": bool(d.get("final")),
                        "final_on": d.get("final_on"),
                        "retrospective": bool(d.get("retrospective")),
                        "forms": d.get("forms"), "suppliers": d.get("suppliers"),
                        "suppliers_named": d.get("suppliers_named"),
                        "json": f"{STATEMENTS_DIR}/{ym}.json",
                        "md": f"{STATEMENTS_DIR}/{ym}.md",
                        "url": f"{BLOB}{STATEMENTS_DIR}/{ym}.md"})
    wd = os.path.join(sdir, WEEKLY_DIR)
    for name in sorted(os.listdir(wd)) if os.path.isdir(wd) else []:
        if not re.fullmatch(r"\d{4}-W\d{2}-" + LYNAS + r"\.json", name):
            continue
        d = _read_json(os.path.join(wd, name))
        if not d or not d.get("generated_on") or (dated and d["generated_on"] > dated):
            continue
        stem = name[:-5]
        weekly.append({"week": d.get("week"), "from": d.get("from"), "to": d.get("to"),
                       "updated_after": (d.get("updated_on") if dated and
                                         (d.get("updated_on") or "") > dated else None),
                       "supplier": LYNAS, "generated_on": d["generated_on"],
                       "final": bool(d.get("final")), "forms": d.get("forms"),
                       "rate": d.get("rate"),
                       "md": f"{STATEMENTS_DIR}/{WEEKLY_DIR}/{stem}.md",
                       "url": f"{BLOB}{STATEMENTS_DIR}/{WEEKLY_DIR}/{stem}.md"})
    monthly.sort(key=lambda x: x["month"], reverse=True)
    weekly.sort(key=lambda x: x["week"] or "", reverse=True)
    return {"monthly": monthly, "weekly": weekly}


def kr5_variants(idx, today, pull_month, score, mvar, first_month=STATEMENTS_FIRST_MONTH):
    """OO3 KR5's month variants. The month a variant carries is the month the
    statement DESCRIBES; its value is the day of the following month it was
    generated on (day 1 = the 1st; past the month's end it keeps counting).

    score(value) -> 0/50/80/100 (okr_score with band 'audit'); mvar(m, **kw) the
    bake's variant constructor.
    """
    by_m = {x["month"]: x for x in (idx or {}).get("monthly") or []}
    out = []
    m = first_month
    while m <= pull_month:
        st = by_m.get(m)
        due = f"{next_month(m)}-01"
        nxt = mlabel(next_month(m))
        link = ({"href": st["url"], "label": f"{mlabel(m)} statement"} if st else None)
        if m < STATEMENTS_SCORED_FROM:
            out.append(mvar(m, link=link, not_measured=(
                "not scored - supplier statements began with Phase 2 in October 2026, so no "
                f"statement for {mlabel(m)} existed by its due date"
                + (f"; one was generated retrospectively on {st['generated_on']}" if st else ""))))
        elif st:
            # BEFORE the pull-month branch: a bake on the 1st whose newest pull
            # is still the 31st has the pull month = the statement's month, and
            # must score the statement that exists, not call it "not due yet".
            day = (datetime.date.fromisoformat(st["generated_on"])
                   - datetime.date.fromisoformat(due)).days + 1
            s = score(day)
            out.append(mvar(m, value=day, display=f"day {day} ({short_day(st['generated_on'])})",
                            score=s, link=link,
                            basis=(f"{mlabel(m)}'s supplier statement was generated on "
                                   f"{st['generated_on']}, day {day} of {nxt} - 100 by the 3rd, "
                                   f"50 by the 10th, 0 after. It is "
                                   + (("FINAL" if (st.get("final_on") or st["generated_on"])
                                       <= st["generated_on"] else
                                       f"PROVISIONAL when generated and FINAL since "
                                       f"{st['final_on']}") if st["final"] else
                                      "PROVISIONAL (the issue feed had not reached the month "
                                      "end; later bakes refresh it)")
                                   + f": {st.get('forms')} issue form(s) naming "
                                     f"{st.get('suppliers_named')} supplier(s)"
                                   + (f". The copy on disk was last updated on "
                                      f"{st['updated_after']}, after this snapshot's date, so "
                                      "its status and counts are as of then"
                                      if st.get("updated_after") else ""))))
        elif m == pull_month:
            _last = next((v for v in reversed(out) if v.get("score") is not None), None)
            out.append(mvar(m, mtd=True, score=None, coverage_days=None,
                            basis=(f"not due yet - {mlabel(m)}'s supplier statement is generated "
                                   f"by the first bake on or after 1 {nxt}, and scores 100 if "
                                   f"that is by the 3rd, 50 by the 10th, 0 after"
                                   + (f". Last scored: {mlabel(_last['m'])}, {_last['display']}, "
                                      f"{_last['score']}" if _last else ""))))
        else:
            day = (datetime.date.fromisoformat(today[:10])
                   - datetime.date.fromisoformat(due)).days + 1
            # the band decides, not this function: a missing statement is a
            # final 0 once even a statement generated today would score 0
            if score(day) == 0:
                out.append(mvar(m, value=day, display=f"none by day {day}", score=score(day),
                                basis=(f"no supplier statement for {mlabel(m)} had been generated "
                                       f"by {today[:10]}, day {day} of {nxt}, so it scores 0 "
                                       "whenever it appears. A late statement is still written by a live "
                                       f"bake within {MONTH_LOOKBACK} months of the month's end")))
            else:
                out.append(mvar(m, not_measured=(
                    f"pending - {mlabel(m)}'s statement is due on 1-3 {nxt} and none has been "
                    f"generated yet (day {max(day, 0)})"
                    + (f" - it can now score at most {score(day)}"
                       if 0 < score(day) < score(1) else ""))))
        m = next_month(m)
    return out
